async def seed_words_to_db():
    """Заполняет таблицу words из LESSONS при первом запуске."""
    import aiosqlite
    from database import DB_PATH
    async with aiosqlite.connect(DB_PATH) as db:
        async with db.execute("SELECT COUNT(*) FROM words") as cur:
            count = (await cur.fetchone())[0]
            if count > 0:
                return
        for lesson_id, lesson in LESSONS.items():
            day_num = int(lesson_id.replace("day", ""))
            for vn, tr, ru, ex_vn, ex_tr, ex_ru in lesson["vocab"]:
                await db.execute(
                    "INSERT INTO words (day, vn, transcription, ru, "
                    "example_vn, example_tr, example_ru) "
                    "VALUES (?, ?, ?, ?, ?, ?, ?)",
                    (day_num, vn, tr, ru, ex_vn, ex_tr, ex_ru)
                )
        await db.commit()
        print(f"✅ Засеяно слов в БД")